"""Rebuild the learning guide's replay data and optional real-video GIF previews."""
from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

from axe_control.decisions import StrictModel
from axe_control.models import Event
from benchmarks.summarize import Episode, evaluate, saved_proof_issues

ROOT = Path(__file__).resolve().parents[1]
MEDIA = ROOT / "docs/media"
RECORDINGS = ROOT / "results/native-comparison"


class Lesson(StrictModel):
    cell: str
    title: str
    model: str
    mode: str
    strict_pass: bool
    outcome_reached: bool
    reason: str
    elapsed_seconds: float
    video_seconds: float
    video: str
    poster: str
    evidence: str
    events: list[Event]


TITLES = {
    "gpt-direct": "Direct LLM tools",
    "clef-tree": "Clef + accessibility",
    "clef-grid": "Clef + screenshot grid",
    "jev-tree": "Jev + accessibility",
    "winnow-direct": "Winnow direct tools",
    "winnow-tree": "Winnow + accessibility",
    "winnow-grid": "Winnow + screenshot grid",
}


def lessons() -> list[Lesson]:
    result: list[Lesson] = []
    for cell, title in TITLES.items():
        folder = RECORDINGS / cell / "basic/repeat-0"
        episode = Episode.model_validate_json((folder / "episode.json").read_text())
        report = episode.report
        if report is None:
            raise ValueError(f"Missing controller report: {cell}")
        video = folder / "original.mp4"
        duration = float(subprocess.check_output([
            "ffprobe", "-v", "error", "-show_entries", "format=duration",
            "-of", "default=noprint_wrappers=1:nokey=1", str(video),
        ], text=True).strip())
        checked = evaluate(episode.scenario, episode.seed, episode.screen,
                           episode.evaluation.oracle, episode.evaluation.tree)
        strict_pass = not episode.issues() and not saved_proof_issues(episode, folder)
        result.append(Lesson(
            cell=cell, title=title, model=episode.provider_config.model,
            mode=episode.provider_config.mode, strict_pass=strict_pass,
            outcome_reached=checked.passed,
            reason=report.reason, elapsed_seconds=report.elapsed_seconds,
            video_seconds=duration,
            video="../" + video.relative_to(ROOT).as_posix(),
            poster="../" + (folder / "final.png").relative_to(ROOT).as_posix(),
            evidence="../" + (folder / "episode.json").relative_to(ROOT).as_posix(),
            events=report.events,
        ))
    return result


def write_data() -> None:
    MEDIA.mkdir(parents=True, exist_ok=True)
    payload = json.dumps([lesson.model_dump() for lesson in lessons()], indent=2)
    (MEDIA / "replays.js").write_text("// Generated by tools/build_learning_media.py.\n"
                                       "const recordedLessons = " + payload + ";\n")


def previews() -> None:
    for cell in ("gpt-direct", "clef-tree", "clef-grid"):
        source = RECORDINGS / cell / "basic/repeat-0/original.mp4"
        subprocess.run([
            "ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(source),
            "-filter_complex",
            "fps=4,scale=220:-1:flags=lanczos,split[a][b];"
            "[a]palettegen=max_colors=96[p];[b][p]paletteuse=dither=bayer",
            "-loop", "0", str(MEDIA / f"{cell}.gif"),
        ], check=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--previews", action="store_true", help="Also regenerate GIFs with FFmpeg")
    options = parser.parse_args()
    write_data()
    if options.previews:
        previews()
    print("Rebuilt seven replay manifests" + (" and three real-video previews" if options.previews
                                              else ""))


if __name__ == "__main__":
    main()
